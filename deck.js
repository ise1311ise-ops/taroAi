export function buildDeck78() {
  const majors = [
    "Шут","Маг","Верховная Жрица","Императрица","Император","Иерофант","Влюблённые","Колесница",
    "Сила","Отшельник","Колесо Фортуны","Правосудие","Повешенный","Смерть","Умеренность",
    "Дьявол","Башня","Звезда","Луна","Солнце","Суд","Мир"
  ].map((name, i) => ({
    id: `M${i}`,
    name: `${i}. ${name}`,
    meta: majorKeywords(name)
  }));

  const suits = [
    { key:"W", name:"Жезлы", meta:"энергия, действие, мотивация, рост" },
    { key:"C", name:"Кубки", meta:"чувства, отношения, интуиция, эмпатия" },
    { key:"S", name:"Мечи",  meta:"мысли, выбор, конфликт, ясность" },
    { key:"P", name:"Пентакли", meta:"деньги, работа, тело, стабильность" }
  ];

  const ranks = [
    { id:"A", name:"Туз", meta:"начало, импульс, шанс" },
    { id:"2", name:"Двойка", meta:"выбор, баланс, союз" },
    { id:"3", name:"Тройка", meta:"рост, кооперация, результат" },
    { id:"4", name:"Четвёрка", meta:"стабильность, границы, пауза" },
    { id:"5", name:"Пятёрка", meta:"напряжение, урок, пересборка" },
    { id:"6", name:"Шестёрка", meta:"движение, помощь, гармонизация" },
    { id:"7", name:"Семёрка", meta:"стратегия, испытание, защита" },
    { id:"8", name:"Восьмёрка", meta:"ускорение, практика, мастерство" },
    { id:"9", name:"Девятка", meta:"созревание, тревога/надежда, итог" },
    { id:"10", name:"Десятка", meta:"кульминация, завершение цикла" },
    { id:"Pg", name:"Паж", meta:"учёба, сообщение, новый опыт" },
    { id:"Kn", name:"Рыцарь", meta:"движение, поступок, импульс" },
    { id:"Q", name:"Королева", meta:"внутренняя зрелость, забота/контроль" },
    { id:"K", name:"Король", meta:"управление, ответственность, стратегия" }
  ];

  const minors = [];
  for (const s of suits) {
    for (const r of ranks) {
      minors.push({
        id: `${s.key}-${r.id}`,
        name: `${r.name} ${s.name}`,
        meta: `${s.meta}; ${r.meta}`
      });
    }
  }

  return [...majors, ...minors];
}

